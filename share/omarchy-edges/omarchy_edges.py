#!/usr/bin/env python3
"""Crop Hyprland's usable area into the healthy part of a damaged panel.

Margins are logical/layout pixels (Hyprland reserved units). On a scale-2
Retina panel, ~56 logical px ≈ 0.5 inch.
"""

from __future__ import annotations

import argparse
import json
import os
import signal
import subprocess
import sys
from dataclasses import asdict, dataclass
from pathlib import Path
from typing import Optional

CONFIG_PATH = Path.home() / ".config/omarchy/omarchy-edges.json"
LEGACY_CONFIG_PATH = Path.home() / ".config/omarchy/screen-safe-zone.json"
LUA_INC_PATH = Path.home() / ".config/hypr/omarchy-edges.inc.lua"
PID_PATH = Path.home() / ".cache/omarchy-edges-mask.pid"
LAYER_NS = "omarchy-edges-mask"
DEFAULT_MONITOR = "eDP-1"

# Conservative starter (~1/3" top/bottom + top-right). Tune in the GUI.
DEFAULT_MARGINS = {"top": 40, "bottom": 50, "left": 0, "right": 90}


@dataclass
class Zone:
    monitor: str = DEFAULT_MONITOR
    top: int = 0
    bottom: int = 0
    left: int = 0
    right: int = 0
    mask: bool = True

    def clamp_to(self, width: int, height: int) -> "Zone":
        max_x = max(0, width - 80)
        max_y = max(0, height - 80)
        self.left = _clamp(self.left, 0, max_x)
        self.right = _clamp(self.right, 0, max_x - self.left)
        self.top = _clamp(self.top, 0, max_y)
        self.bottom = _clamp(self.bottom, 0, max_y - self.top)
        return self


def _clamp(v: int, lo: int, hi: int) -> int:
    return max(lo, min(int(v), hi))


def _run(cmd: list[str], check: bool = True) -> subprocess.CompletedProcess:
    return subprocess.run(cmd, check=check, text=True, capture_output=True)


def hypr_json(cmd: list[str]):
    out = _run(["hyprctl", "-j", *cmd]).stdout
    return json.loads(out)


def focused_monitor() -> dict:
    monitors = hypr_json(["monitors"])
    for m in monitors:
        if m.get("focused"):
            return m
    return monitors[0]


def layout_size(mon: dict) -> tuple[int, int, float]:
    scale = float(mon.get("scale") or 1) or 1.0
    # hyprctl width/height are physical; reserved & layers use layout px.
    w = int(round(mon["width"] / scale))
    h = int(round(mon["height"] / scale))
    return w, h, scale


def load_zone() -> Zone:
    path = CONFIG_PATH if CONFIG_PATH.exists() else LEGACY_CONFIG_PATH
    if not path.exists():
        return Zone(**DEFAULT_MARGINS)
    data = json.loads(path.read_text())
    z = Zone(
        monitor=data.get("monitor", DEFAULT_MONITOR),
        top=int(data.get("top", 0)),
        bottom=int(data.get("bottom", 0)),
        left=int(data.get("left", 0)),
        right=int(data.get("right", 0)),
        mask=bool(data.get("mask", True)),
    )
    return z


def save_zone(zone: Zone) -> None:
    CONFIG_PATH.parent.mkdir(parents=True, exist_ok=True)
    CONFIG_PATH.write_text(json.dumps(asdict(zone), indent=2) + "\n")
    LUA_INC_PATH.parent.mkdir(parents=True, exist_ok=True)
    LUA_INC_PATH.write_text(
        "-- Auto-generated by omarchy-edges. Do not edit by hand.\n"
        "return {\n"
        f"  top = {int(zone.top)},\n"
        f"  bottom = {int(zone.bottom)},\n"
        f"  left = {int(zone.left)},\n"
        f"  right = {int(zone.right)},\n"
        "}\n"
    )


def apply_reserved(zone: Zone) -> None:
    mon = zone.monitor
    scale = 2.0
    for m in hypr_json(["monitors"]):
        if m["name"] == mon:
            scale = float(m.get("scale") or 2) or 2.0
            break

    def _eval_once() -> None:
        lua = (
            "hl.monitor({"
            f"output={json.dumps(mon)}, "
            "mode='preferred', position='auto', "
            f"scale={scale:g}, "
            "reserved={"
            f"top={int(zone.top)}, bottom={int(zone.bottom)}, "
            f"left={int(zone.left)}, right={int(zone.right)}"
            "}"
            "})"
        )
        res = _run(["hyprctl", "eval", lua])
        if res.returncode != 0 or "ok" not in (res.stdout + res.stderr):
            raise RuntimeError(res.stdout + res.stderr or "hyprctl eval failed")

    def _matches() -> bool:
        for m in hypr_json(["monitors"]):
            if m["name"] != mon:
                continue
            # hyprctl reserved is [left, top, right, bottom]; top includes the bar.
            left, top, right, bottom = m.get("reserved") or [0, 0, 0, 0]
            return (
                left >= zone.left
                and right >= zone.right
                and bottom >= zone.bottom
                and top >= zone.top
            )
        return False

    # Apply twice if needed — Hyprland can drop one edge when bars also reserve.
    for _ in range(3):
        _eval_once()
        if _matches():
            return
    if not _matches():
        raise RuntimeError(
            f"omarchy-edges reserved did not stick for {mon}: wanted "
            f"T{zone.top} B{zone.bottom} L{zone.left} R{zone.right}"
        )


def notify(msg: str) -> None:
    subprocess.run(
        ["notify-send", "-a", "omarchy-edges", "-u", "low", "omarchy-edges", msg],
        check=False,
    )


def kill_mask() -> None:
    if PID_PATH.exists():
        try:
            pid = int(PID_PATH.read_text().strip())
            os.kill(pid, signal.SIGTERM)
        except (ValueError, ProcessLookupError, PermissionError):
            pass
        try:
            PID_PATH.unlink()
        except FileNotFoundError:
            pass
    # Also kill any leftover mask processes by namespace owner
    subprocess.run(["pkill", "-f", "omarchy_edges.py mask"], check=False)


def start_mask(zone: Zone) -> None:
    kill_mask()
    if not zone.mask or (zone.top == zone.bottom == zone.left == zone.right == 0):
        return
    env = os.environ.copy()
    env["LD_PRELOAD"] = "/usr/lib/libgtk4-layer-shell.so"
    proc = subprocess.Popen(
        [sys.executable, str(Path(__file__)), "mask", "--daemon"],
        env=env,
        start_new_session=True,
        stdout=subprocess.DEVNULL,
        stderr=subprocess.DEVNULL,
    )
    PID_PATH.parent.mkdir(parents=True, exist_ok=True)
    PID_PATH.write_text(str(proc.pid))


def apply_zone(zone: Zone, *, persist: bool = True, restart_mask: bool = True) -> Zone:
    mon = focused_monitor()
    # Prefer configured monitor if present
    for m in hypr_json(["monitors"]):
        if m["name"] == zone.monitor:
            mon = m
            break
    else:
        zone.monitor = mon["name"]
    w, h, _ = layout_size(mon)
    zone.clamp_to(w, h)
    if persist:
        save_zone(zone)
    apply_reserved(zone)
    if restart_mask:
        start_mask(zone)
    return zone


def select_with_slurp(zone: Zone) -> Zone:
    mon = None
    for m in hypr_json(["monitors"]):
        if m["name"] == zone.monitor:
            mon = m
            break
    if mon is None:
        mon = focused_monitor()
        zone.monitor = mon["name"]
    w, h, scale = layout_size(mon)
    # slurp speaks in surface/global coords; on this setup windows use layout px.
    # Prefer geometry relative to monitor origin in layout space.
    ox, oy = int(mon["x"]), int(mon["y"])
    # Reset crop while selecting so the user can see full panel damage edges.
    apply_reserved(Zone(monitor=zone.monitor, mask=False))
    try:
        raw = _run(
            [
                "slurp",
                "-b",
                "00000066",
                "-c",
                "89b4faff",
                "-w",
                "2",
                "-f",
                "%x %y %w %h",
            ]
        ).stdout.strip()
    except subprocess.CalledProcessError:
        apply_zone(zone, persist=False)
        raise SystemExit("Selection cancelled")
    if not raw:
        apply_zone(zone, persist=False)
        raise SystemExit("Selection cancelled")
    x, y, sw, sh = map(int, raw.split())
    phys_w, phys_h = int(mon["width"]), int(mon["height"])
    # Hyprland+slurp may report either layout or physical pixels. Pick the
    # interpretation whose selection size is closer to that space.
    layout_score = abs(sw - w) + abs(sh - h)
    physical_score = abs(sw - phys_w) + abs(sh - phys_h)
    if physical_score < layout_score and scale != 1:
        lx = int(round((x - ox) / scale))
        ly = int(round((y - oy) / scale))
        lw = int(round(sw / scale))
        lh = int(round(sh / scale))
    else:
        # Assume layout/global layout coordinates.
        lx, ly, lw, lh = x - ox, y - oy, sw, sh
        # If monitor origin is also physical, convert origin.
        if ox > w or oy > h:
            lx = int(round((x - ox) / scale))
            ly = int(round((y - oy) / scale))
    zone.left = max(0, lx)
    zone.top = max(0, ly)
    zone.right = max(0, w - (lx + lw))
    zone.bottom = max(0, h - (ly + lh))
    return zone.clamp_to(w, h)


def cmd_status(_: argparse.Namespace) -> int:
    zone = load_zone()
    mon = focused_monitor()
    w, h, scale = layout_size(mon)
    reserved = mon.get("reserved")
    print(f"monitor:   {zone.monitor} (focused {mon['name']})")
    print(f"layout:    {w}x{h} @ scale {scale}")
    print(f"margins:   top={zone.top} bottom={zone.bottom} left={zone.left} right={zone.right}")
    print(f"usable:    {w - zone.left - zone.right}x{h - zone.top - zone.bottom}")
    print(f"mask:      {zone.mask}")
    print(f"hypr reserved (L,T,R,B): {reserved}")
    print(f"config:    {CONFIG_PATH}")
    return 0


def cmd_apply(_: argparse.Namespace) -> int:
    zone = apply_zone(load_zone())
    notify(
        f"omarchy-edges on {zone.monitor}: "
        f"T{zone.top} B{zone.bottom} L{zone.left} R{zone.right}"
    )
    print(asdict(zone))
    return 0


def cmd_reset(_: argparse.Namespace) -> int:
    zone = Zone(monitor=load_zone().monitor, mask=True)
    apply_zone(zone)
    notify("omarchy-edges cleared — full panel usable again")
    print(asdict(zone))
    return 0


def cmd_select(_: argparse.Namespace) -> int:
    zone = load_zone()
    notify("Drag a rectangle over the healthy part of the screen")
    zone = select_with_slurp(zone)
    apply_zone(zone)
    notify(
        f"Applied: T{zone.top} B{zone.bottom} L{zone.left} R{zone.right}"
    )
    print(asdict(zone))
    return 0


def cmd_set(args: argparse.Namespace) -> int:
    zone = load_zone()
    for key in ("top", "bottom", "left", "right"):
        val = getattr(args, key)
        if val is not None:
            setattr(zone, key, val)
    if args.monitor:
        zone.monitor = args.monitor
    if args.mask is not None:
        zone.mask = args.mask
    apply_zone(zone)
    print(asdict(zone))
    return 0


def run_mask_daemon() -> int:
    import gi

    gi.require_version("Gtk", "4.0")
    gi.require_version("Gtk4LayerShell", "1.0")
    from gi.repository import Gtk, GLib, Gdk
    from gi.repository import Gtk4LayerShell as LS

    zone = load_zone()
    mon_name = zone.monitor

    css = Gtk.CssProvider()
    css.load_from_data(
        b"""
        .safe-mask { background-color: #000000; }
        """
    )
    display = Gdk.Display.get_default()
    Gtk.StyleContext.add_provider_for_display(
        display, css, Gtk.STYLE_PROVIDER_PRIORITY_APPLICATION
    )

    windows: list[Gtk.Window] = []

    def make_edge(edge: str, size: int) -> Optional[Gtk.Window]:
        if size <= 0:
            return None
        win = Gtk.Window()
        LS.init_for_window(win)
        LS.set_namespace(win, LAYER_NS)
        LS.set_layer(win, LS.Layer.OVERLAY)
        LS.set_exclusive_zone(win, -1)
        LS.set_keyboard_mode(win, LS.KeyboardMode.NONE)
        # Bind to the damaged laptop panel when possible.
        try:
            for monitor in display.get_monitors():
                # Gdk.Monitor connector isn't always exposed; anchor all edges on primary.
                pass
        except Exception:
            pass

        if edge == "top":
            LS.set_anchor(win, LS.Edge.TOP, True)
            LS.set_anchor(win, LS.Edge.LEFT, True)
            LS.set_anchor(win, LS.Edge.RIGHT, True)
            win.set_default_size(10, size)
        elif edge == "bottom":
            LS.set_anchor(win, LS.Edge.BOTTOM, True)
            LS.set_anchor(win, LS.Edge.LEFT, True)
            LS.set_anchor(win, LS.Edge.RIGHT, True)
            win.set_default_size(10, size)
        elif edge == "left":
            LS.set_anchor(win, LS.Edge.LEFT, True)
            LS.set_anchor(win, LS.Edge.TOP, True)
            LS.set_anchor(win, LS.Edge.BOTTOM, True)
            win.set_default_size(size, 10)
        elif edge == "right":
            LS.set_anchor(win, LS.Edge.RIGHT, True)
            LS.set_anchor(win, LS.Edge.TOP, True)
            LS.set_anchor(win, LS.Edge.BOTTOM, True)
            win.set_default_size(size, 10)

        box = Gtk.Box()
        box.add_css_class("safe-mask")
        box.set_hexpand(True)
        box.set_vexpand(True)
        if edge in ("top", "bottom"):
            box.set_size_request(-1, size)
        else:
            box.set_size_request(size, -1)
        win.set_child(box)
        win.present()
        return win

    for edge, size in (
        ("top", zone.top),
        ("bottom", zone.bottom),
        ("left", zone.left),
        ("right", zone.right),
    ):
        w = make_edge(edge, size)
        if w:
            windows.append(w)

    def on_signal(signum, frame):
        for w in windows:
            w.destroy()
        Gtk.Application.get_default()
        loop.quit()

    signal.signal(signal.SIGTERM, on_signal)
    signal.signal(signal.SIGINT, on_signal)

    # Reload masks when config changes (mtime poll — simple & reliable).
    last_mtime = CONFIG_PATH.stat().st_mtime if CONFIG_PATH.exists() else 0

    def poll_config():
        nonlocal last_mtime, windows, zone
        try:
            mtime = CONFIG_PATH.stat().st_mtime
        except FileNotFoundError:
            return True
        if mtime == last_mtime:
            return True
        last_mtime = mtime
        zone = load_zone()
        for w in windows:
            w.destroy()
        windows = []
        for edge, size in (
            ("top", zone.top),
            ("bottom", zone.bottom),
            ("left", zone.left),
            ("right", zone.right),
        ):
            w = make_edge(edge, size)
            if w:
                windows.append(w)
        return True

    loop = GLib.MainLoop()
    GLib.timeout_add(1000, poll_config)
    loop.run()
    return 0


def cmd_gui(_: argparse.Namespace) -> int:
    import gi

    gi.require_version("Gtk", "4.0")
    gi.require_version("Adw", "1")
    from gi.repository import Gtk, Adw, GLib

    Adw.init()
    zone = load_zone()
    mon = focused_monitor()
    for m in hypr_json(["monitors"]):
        if m["name"] == zone.monitor:
            mon = m
            break
    width, height, scale = layout_size(mon)
    zone.clamp_to(width, height)

    # Fit inside the already-cropped usable area (leave room for bar + gaps).
    usable_h = max(320, height - zone.top - zone.bottom - 40)
    usable_w = max(360, width - zone.left - zone.right - 40)
    win_w = min(460, usable_w)
    win_h = min(520, usable_h)

    app = Adw.Application(application_id="org.omarchy.edges")
    apply_timeout: Optional[int] = None
    top_adj = bottom_adj = left_adj = right_adj = mask_switch = preview = usable_lbl = None  # type: ignore

    def current_zone() -> Zone:
        return Zone(
            monitor=zone.monitor,
            top=int(top_adj.get_value()),
            bottom=int(bottom_adj.get_value()),
            left=int(left_adj.get_value()),
            right=int(right_adj.get_value()),
            mask=mask_switch.get_active(),
        )

    def recenter_window():
        subprocess.run(
            ["hyprctl", "dispatch", "focuswindow", "class:org.omarchy.edges"],
            check=False,
            capture_output=True,
        )
        subprocess.run(
            ["hyprctl", "dispatch", "centerwindow"],
            check=False,
            capture_output=True,
        )

    def schedule_live_apply():
        nonlocal apply_timeout

        def _apply():
            nonlocal apply_timeout
            apply_timeout = None
            z = current_zone()
            try:
                apply_zone(z, persist=False, restart_mask=True)
            except Exception as exc:
                notify(f"Apply failed: {exc}")
            update_preview()
            usable_lbl.set_label(
                f"Usable {width - z.left - z.right}×{height - z.top - z.bottom}  ·  "
                f"panel {width}×{height} @ {scale:g}x\n"
                "Lower Top if the black bar covers healthy screen."
            )
            GLib.timeout_add(80, lambda: (recenter_window(), False)[1])
            return False

        if apply_timeout:
            GLib.source_remove(apply_timeout)
        apply_timeout = GLib.timeout_add(150, _apply)

    def update_preview():
        if preview:
            preview.queue_draw()

    def on_draw(area, cr, w, h):
        t = int(top_adj.get_value())
        b = int(bottom_adj.get_value())
        l = int(left_adj.get_value())
        r = int(right_adj.get_value())
        cr.set_source_rgb(0.12, 0.12, 0.14)
        cr.rectangle(0, 0, w, h)
        cr.fill()
        cr.set_source_rgb(0.45, 0.12, 0.12)
        sx = w / width
        sy = h / height
        cr.rectangle(0, 0, w, t * sy)
        cr.rectangle(0, h - b * sy, w, b * sy)
        cr.rectangle(0, 0, l * sx, h)
        cr.rectangle(w - r * sx, 0, r * sx, h)
        cr.fill()
        cr.set_source_rgb(0.20, 0.45, 0.28)
        cr.rectangle(l * sx, t * sy, max(0, w - (l + r) * sx), max(0, h - (t + b) * sy))
        cr.fill()
        cr.set_source_rgb(0.9, 0.9, 0.92)
        cr.select_font_face("Sans", 0, 0)
        cr.set_font_size(12)
        cr.move_to(10, 18)
        cr.show_text("Red = covered   Green = usable")
        return False

    def persist_and_close(win):
        z = current_zone()
        apply_zone(z, persist=True, restart_mask=True)
        notify(f"Saved omarchy-edges: T{z.top} B{z.bottom} L{z.left} R{z.right}")
        win.close()

    def on_activate(app: Adw.Application):
        nonlocal top_adj, bottom_adj, left_adj, right_adj, mask_switch, preview, usable_lbl

        win = Adw.ApplicationWindow(application=app, title="omarchy-edges")
        win.set_default_size(win_w, win_h)
        win.set_size_request(360, 280)

        toolbar = Adw.ToolbarView()
        header = Adw.HeaderBar()
        header.set_title_widget(Gtk.Label(label="omarchy-edges"))
        toolbar.add_top_bar(header)

        box = Gtk.Box(
            orientation=Gtk.Orientation.VERTICAL,
            spacing=10,
            margin_top=12,
            margin_bottom=12,
            margin_start=14,
            margin_end=14,
        )

        intro = Gtk.Label(
            label="Drag sliders to keep UI inside undamaged glass. "
            "Scroll this window if controls are clipped.",
            wrap=True,
            xalign=0,
        )
        intro.add_css_class("dim-label")
        box.append(intro)

        preview = Gtk.DrawingArea()
        preview.set_content_width(400)
        preview.set_content_height(140)
        preview.set_hexpand(True)
        preview.set_draw_func(on_draw)
        frame = Gtk.Frame()
        frame.set_child(preview)
        box.append(frame)

        usable_lbl = Gtk.Label(xalign=0, wrap=True)
        box.append(usable_lbl)

        def make_scale(label: str, value: int, upper: int):
            row = Gtk.Box(orientation=Gtk.Orientation.VERTICAL, spacing=2)
            head = Gtk.Box(orientation=Gtk.Orientation.HORIZONTAL)
            lab = Gtk.Label(label=label, xalign=0, hexpand=True)
            val = Gtk.Label(label=str(value))
            head.append(lab)
            head.append(val)
            adj = Gtk.Adjustment(
                value=value, lower=0, upper=upper, step_increment=1, page_increment=5
            )
            sc = Gtk.Scale(orientation=Gtk.Orientation.HORIZONTAL, adjustment=adj)
            sc.set_draw_value(False)
            sc.set_hexpand(True)
            sc.set_size_request(-1, 28)

            def changed(*_):
                val.set_text(str(int(adj.get_value())))
                schedule_live_apply()

            adj.connect("value-changed", changed)
            row.append(head)
            row.append(sc)
            box.append(row)
            return adj

        max_y = max(0, height - 80)
        max_x = max(0, width - 80)
        top_adj = make_scale("Top margin", zone.top, max_y)
        bottom_adj = make_scale("Bottom margin", zone.bottom, max_y)
        left_adj = make_scale("Left margin", zone.left, max_x)
        right_adj = make_scale("Right margin", zone.right, max_x)

        mask_row = Gtk.Box(orientation=Gtk.Orientation.HORIZONTAL, spacing=8)
        mask_row.append(Gtk.Label(label="Black out damaged edges", xalign=0, hexpand=True))
        mask_switch = Gtk.Switch()
        mask_switch.set_active(zone.mask)
        mask_switch.set_valign(Gtk.Align.CENTER)
        mask_switch.connect("notify::active", lambda *_: schedule_live_apply())
        mask_row.append(mask_switch)
        box.append(mask_row)

        buttons = Gtk.Box(orientation=Gtk.Orientation.HORIZONTAL, spacing=8)
        buttons.set_homogeneous(False)

        def on_select(*_):
            win.hide()

            def after():
                try:
                    z = select_with_slurp(current_zone())
                    top_adj.set_value(z.top)
                    bottom_adj.set_value(z.bottom)
                    left_adj.set_value(z.left)
                    right_adj.set_value(z.right)
                    apply_zone(z, persist=False, restart_mask=True)
                    update_preview()
                except SystemExit:
                    apply_zone(load_zone(), persist=False, restart_mask=True)
                finally:
                    win.present()
                    GLib.timeout_add(100, lambda: (recenter_window(), False)[1])
                return False

            GLib.timeout_add(150, after)

        def set_margins(t, b, l, r):
            top_adj.set_value(t)
            bottom_adj.set_value(b)
            left_adj.set_value(l)
            right_adj.set_value(r)

        select_btn = Gtk.Button(label="Select…")
        select_btn.connect("clicked", on_select)
        buttons.append(select_btn)

        half_btn = Gtk.Button(label="Starter")
        half_btn.connect(
            "clicked",
            lambda *_: set_margins(
                DEFAULT_MARGINS["top"],
                DEFAULT_MARGINS["bottom"],
                DEFAULT_MARGINS["left"],
                DEFAULT_MARGINS["right"],
            ),
        )
        buttons.append(half_btn)

        reset_btn = Gtk.Button(label="Reset")
        reset_btn.connect("clicked", lambda *_: set_margins(0, 0, 0, 0))
        buttons.append(reset_btn)

        save_btn = Gtk.Button(label="Save")
        save_btn.add_css_class("suggested-action")
        save_btn.set_hexpand(True)
        save_btn.connect("clicked", lambda *_: persist_and_close(win))
        buttons.append(save_btn)
        box.append(buttons)

        scroll = Gtk.ScrolledWindow()
        scroll.set_policy(Gtk.PolicyType.NEVER, Gtk.PolicyType.AUTOMATIC)
        scroll.set_propagate_natural_height(True)
        scroll.set_child(box)
        # Make sure touchpad/mouse wheel always scroll the editor, not a parent.
        scroll.set_vexpand(True)
        scroll.set_hexpand(True)

        toolbar.set_content(scroll)
        win.set_content(toolbar)
        schedule_live_apply()
        win.present()
        GLib.timeout_add(120, lambda: (recenter_window(), False)[1])

    app.connect("activate", on_activate)
    return app.run(None)


def build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(
        prog="omarchy-edges",
        description="Crop Hyprland content into the healthy region of a damaged panel (omarchy-edges)",
    )
    sub = p.add_subparsers(dest="cmd")

    sub.add_parser("gui", help="Interactive margin editor (default)")
    sub.add_parser("select", help="Draw the healthy rectangle with the mouse")
    sub.add_parser("apply", help="Apply saved omarchy-edges crop")
    sub.add_parser("reset", help="Clear crop (full panel)")
    sub.add_parser("status", help="Show current crop")

    set_p = sub.add_parser("set", help="Set margins in logical pixels")
    set_p.add_argument("--top", type=int)
    set_p.add_argument("--bottom", type=int)
    set_p.add_argument("--left", type=int)
    set_p.add_argument("--right", type=int)
    set_p.add_argument("--monitor")
    set_p.add_argument("--mask", choices=["on", "off"])

    mask_p = sub.add_parser("mask", help="Run black edge masks (internal)")
    mask_p.add_argument("--daemon", action="store_true")

    return p


def main(argv: Optional[list[str]] = None) -> int:
    argv = list(sys.argv[1:] if argv is None else argv)
    parser = build_parser()
    if not argv:
        argv = ["gui"]
    args = parser.parse_args(argv)
    cmd = args.cmd or "gui"

    if cmd == "gui":
        # GUI does not need layer-shell preload; mask subprocess sets it.
        return cmd_gui(args)
    if cmd == "select":
        return cmd_select(args)
    if cmd == "apply":
        return cmd_apply(args)
    if cmd == "reset":
        return cmd_reset(args)
    if cmd == "status":
        return cmd_status(args)
    if cmd == "set":
        if getattr(args, "mask", None) == "on":
            args.mask = True
        elif getattr(args, "mask", None) == "off":
            args.mask = False
        else:
            args.mask = None
        return cmd_set(args)
    if cmd == "mask":
        return run_mask_daemon()
    parser.print_help()
    return 1


if __name__ == "__main__":
    sys.exit(main())
